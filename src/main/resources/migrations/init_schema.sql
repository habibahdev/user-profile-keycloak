create table information (
    id bigint generated by default as identity primary key,
    age integer,
    gender varchar(255),
    situation varchar(255),
    orientation varchar(255)
);

create table social_media (
    social_media_id bigint generated by default as identity primary key,
    platform_name varchar(255)
);

create table users (
    user_id bigint generated by default as identity primary key,
    first_name varchar(255),
    last_name varchar(255),
    pseudo varchar(255),
    birth_date date,
    email unique varchar(255),
    phone varchar(255),
    locale varchar(15),
    latitude double precision,
    longitude double precision,
    location_updates_at timestamp
);

create table profil (
    profil_id bigint generated by default as identity primary key,
    photo varchar(255),
    biography varchar(255),
    user_id bigint unique,
    information_id bigint unique,
    constraint fk_profil_user foreign key (user_id) references users (user_id),
    constraint fk_profil_information foreign key (information_id) references information (id)
);

create table user_social_media (
    user_id bigint not null,
    social_media_id bigint not null,
    profil_link varchar(255),
    constraint pk_user_social_media primary key (user_id, social_media_id),
    constraint fk_user_social_media foreign key (user_id) references users (user_id),
    constraint fk_user_social_media_social_media foreign key (social_media_id) references social_media (social_media_id)
);

create index idx_users_email on users (email);
create index idx_users_pseudo on users (pseudo);
create index idx_user_social_media_social_media_id on user_social_media (social_media_id);